def suma(a:int,b:int)->int:
    """Funcion para sumar dos numeros

    Args:
        a (int): numero entero positivo puede => 0
        b (int): numero entero positivo puede => 0

    Returns:
        None: en caso el valor de a o b sea menor a 0
        int: retorna el resultado de la suma de a+b
    """
    if a<0 or b<0:
        return None
    elif b<0:
        return None
    return a+b

